		<h2 id="helps-title">Some decisions deserve examination before commitment.</h2>
		<p>
			Growth, succession, acquisition, and operating change tend to surface questions that
			were easy to leave implicit before. Several problems may appear urgent. The most
			visible one is not always the one governing the rest.
		</p>
		<p>
			The Constraint Session creates enough distance to examine the situation before
			committing more people, software, money, or management attention.
		</p>
		<ul class="ruled-list">
			<li>Before hiring an operations leader</li>
			<li>After acquiring or stepping into a business</li>
			<li>Before a significant system or organizational change</li>
			<li>When recurring friction has several plausible causes</li>
		</ul>
	</section>

	<section class="prose-section" id="how-it-works" aria-labelledby="works-title">
		<h2 id="works-title">From the flow of the business to one clear priority.</h2>
		<ol class="steps">
			<li>
				<h3>Establish the question</h3>
				<p>
					Define the part of the business under examination and what has made it worth
					addressing now.
				</p>
			</li>
			<li>
				<h3>Trace the relevant flow</h3>
				<p>
					Follow how work, information, and decisions move through the business in practice.
				</p>
			</li>
			<li>
				<h3>Separate cause from symptom</h3>
				<p>
					Identify the recurring points of delay, intervention, ambiguity, or risk, then
					determine which appear to govern the others.
				</p>
			</li>
			<li>
				<h3>Choose the first move</h3>
				<p>
					Rank the alternatives and define the smallest practical intervention worth making
					first.
				</p>
			</li>
		</ol>
	</section>

